    public void addCategory(){
        int row = this.tblItem.getSelectedRow();
        if(row != -1){
            int itemId = (int)this.tblItem.getModel().getValueAt(row, 0);
            String category = (String)this.cboCategory.getSelectedItem();
            int categoryId = (int)this.categoryAndId.get(category);
            this.itemService.addCategoryToItem(itemId, categoryId);
            this.loadAllItem();
        }
    }
    
    
    
    
    
