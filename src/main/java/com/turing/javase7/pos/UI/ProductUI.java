    public void loadAllItem(){
        ArrayList<Item> items = this.itemService.getAllItems();
        DefaultTableModel model = (DefaultTableModel)this.tblItem.getModel();
        model.setRowCount(0);
        for(Item item : items){
            Object[] row = new Object[5];
            row[0] = item.id();
            row[1] = item.name();
            row[2] = item.price();
            row[3] = item.stockAmount();
            row[4] = this.getCategoryForItem(item.id());
            model.addRow(row);
        }
    }
    
    public String getCategoryForItem(int itemId){
        ArrayList<Category> categories = this.categoryService.getAllCategoryByItemId(itemId);
        //System.out.println("categories "+categories);
        String str="";
        for(Category category : categories){
            //System.out.println("category name"+category.name());
            if(str.length()>0){
                str +=", "+category.name();
            }else{
                str +=category.name();
            }
        }
        return str;
    }
    
    public void loadAllCategoryToCboBox(){
        ArrayList<Category> categories = this.categoryService.getAllCategory();
        for(Category category : categories){
            this.cboCategory.addItem(category.name());
            this.categoryAndId.put(category.name(), category.id());
        }
        
    }
    
