    public void addItem(){
        String name = this.txtName.getText();
        int price = Integer.parseInt(this.txtPrice.getText());
        int stockAmount = Integer.parseInt(this.txtStockAmount.getText());
        this.itemService.addItems(name, price, stockAmount);
        this.loadAllItem();
        this.clearForm();
    }
    
    public void clearForm(){
        this.txtName.setText("");
        this.txtPrice.setText("");
        this.txtStockAmount.setText("");
    }
    
