    public void deleteItem(){
        int row = this.tblItem.getSelectedRow();
        if(row != -1){
            int id = (int)this.tblItem.getModel().getValueAt(row, 0);
            this.itemService.deleteItemsById(id);
            this.loadAllItem();
        }
    }
    
